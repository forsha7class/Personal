#!/usr/bin/env node
/**
 * DIKA/OS static site generator.
 *
 * Zero dependencies. Reads content/projects.json plus the page sources in
 * src/, then writes plain HTML into the repository root so GitHub Pages can
 * serve it directly.
 *
 *   node build.mjs           write output
 *   node build.mjs --check   fail if committed output differs from source
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, rmSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(fileURLToPath(import.meta.url));
const CHECK = process.argv.includes("--check");
const MARKER = "<!-- generated by build.mjs — edit src/ or content/projects.json, not this file -->";

const STATUSES = new Set(["research", "development", "testing", "live", "archived"]);
const VISIBILITIES = new Set(["published", "pending-review"]);
const STATUS_LABELS = {
  research: "Research",
  development: "In development",
  testing: "Testing",
  live: "Live",
  archived: "Archived"
};

/* ------------------------------------------------------------------ */
/* input                                                               */
/* ------------------------------------------------------------------ */

const data = JSON.parse(readFileSync(join(ROOT, "content", "projects.json"), "utf8"));
const site = data.site || {};
const stack = Array.isArray(data.stack) ? data.stack : [];
const projects = Array.isArray(data.projects) ? data.projects : [];
const layout = readFileSync(join(ROOT, "templates", "layout.html"), "utf8");

const profilePath = join(ROOT, "content", "profile.json");
const profile = existsSync(profilePath) ? JSON.parse(readFileSync(profilePath, "utf8")) : {};

/* ------------------------------------------------------------------ */
/* validation                                                          */
/* ------------------------------------------------------------------ */

const errors = [];
const notes = [];
const seenSlugs = new Set();

for (const project of projects) {
  const slug = project.slug || "(no slug)";

  if (!project.slug) {
    errors.push("a project entry is missing a slug");
    continue;
  }
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(project.slug)) {
    errors.push(`${slug}: slug must be lower-case kebab-case`);
  }
  if (seenSlugs.has(project.slug)) errors.push(`${slug}: duplicate slug`);
  seenSlugs.add(project.slug);

  if (!STATUSES.has(project.status)) {
    errors.push(`${slug}: invalid status "${project.status}" (expected ${[...STATUSES].join(", ")})`);
  }
  if (!VISIBILITIES.has(project.visibility)) {
    errors.push(`${slug}: invalid visibility "${project.visibility}" (expected ${[...VISIBILITIES].join(", ")})`);
  }

  if (project.visibility === "published") {
    for (const key of ["name", "tagline", "category", "year", "summary"]) {
      if (!project[key]) errors.push(`${slug}: published project is missing "${key}"`);
    }
    if (!Array.isArray(project.technologies) || project.technologies.length === 0) {
      errors.push(`${slug}: published project needs at least one technology`);
    }
    if (!Array.isArray(project.evidence) || project.evidence.length === 0) {
      errors.push(`${slug}: published project needs at least one public evidence link`);
    }
    if (!Array.isArray(project.features) || project.features.length < 2) {
      errors.push(`${slug}: published project needs at least two verified features`);
    }
  } else {
    const missing = ["tagline", "summary", "technologies", "evidence"].filter((key) => {
      const value = project[key];
      return !value || (Array.isArray(value) && value.length === 0);
    });
    notes.push(`${slug}: pending review — withheld from the public build (missing ${missing.join(", ") || "nothing"})`);
  }
}

if (errors.length) {
  console.error("✗ content validation failed:\n");
  for (const error of errors) console.error(`  - ${error}`);
  process.exit(1);
}

/* ------------------------------------------------------------------ */
/* helpers                                                             */
/* ------------------------------------------------------------------ */

const ESCAPES = { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" };
const esc = (value) => String(value).replace(/[&<>"']/g, (char) => ESCAPES[char]);

const published = projects.filter((project) => project.visibility === "published");
const featured = published.filter((project) => project.featured !== false);

const outputs = new Map();
const emit = (relPath, content) => outputs.set(relPath, content);

function fill(template, values) {
  return template.replace(/\{\{(\w+)\}\}/g, (match, key) =>
    Object.prototype.hasOwnProperty.call(values, key) ? values[key] : match
  );
}

function slugOrder(a, b) {
  const order = ["rizzy", "kelapaku", "forsha-7"];
  const ai = order.indexOf(a.slug);
  const bi = order.indexOf(b.slug);
  return (ai === -1 ? 99 : ai) - (bi === -1 ? 99 : bi);
}

/* ------------------------------------------------------------------ */
/* shared chrome                                                       */
/* ------------------------------------------------------------------ */

function header(active) {
  const links = [
    ["home", "/", "Home"],
    ["projects", "/projects/", "Projects"],
    ["stack", "/#stack", "Stack"],
    ["about", "/#about", "About"],
    ["contact", "/#contact", "Contact"]
  ];

  const items = links
    .map(([key, href, label]) => {
      const current = key === active ? ' aria-current="page"' : "";
      return `<a href="${href}"${current}>${label.toUpperCase()}</a>`;
    })
    .join("\n        ");

  return `<header class="header">
  <div class="container header-row">
    <a class="brand" href="/">
      <span class="brand-mark" aria-hidden="true">D</span>
      <span class="brand-text"><b>DIKA/OS</b><small>SYSTEMS BUILDER</small></span>
    </a>
    <nav class="nav" id="siteNav" aria-label="Primary navigation">
        ${items}
    </nav>
    <a class="btn ghost header-cta" href="/#terminal">TERMINAL <kbd>⌘K</kbd></a>
    <button class="nav-toggle" id="navToggle" type="button" aria-label="Open menu" aria-expanded="false" aria-controls="siteNav">
      <span></span><span></span><span></span>
    </button>
  </div>
</header>`;
}

function footer() {
  const links = [
    site.github ? `<a href="${esc(site.github)}" target="_blank" rel="noopener noreferrer">GITHUB ↗</a>` : "",
    site.email ? `<a href="mailto:${esc(site.email)}">EMAIL ↗</a>` : "",
    site.instagram
      ? `<a href="${esc(site.instagram)}" target="_blank" rel="noopener noreferrer">INSTAGRAM ↗</a>`
      : ""
  ]
    .filter(Boolean)
    .join("");

  return `<footer class="footer">
  <div class="container footer-row">
    <span>© <span id="year">2026</span> ${esc(site.name || "DIKA/OS")}</span>
    <span class="footer-links">${links}</span>
    <span>STATIC · NO TRACKING</span>
  </div>
</footer>`;
}

function page({ path, title, description, body, active, ogType = "website", extraHead = "" }) {
  const canonical = `${site.url}${path}`;
  const values = {
    title: esc(title),
    description: esc(description),
    canonical: esc(canonical),
    ogType,
    siteName: esc(site.name || "DIKA/OS"),
    ogImage: `${site.url}/assets/og.jpg`,
    header: header(active),
    footer: footer(),
    body,
    extraHead
  };

  return `${MARKER}\n${fill(layout, values)}`;
}

/* ------------------------------------------------------------------ */
/* project fragments                                                   */
/* ------------------------------------------------------------------ */

function statusChip(status) {
  return `<span class="status-chip" data-status="${esc(status)}">${STATUS_LABELS[status]}</span>`;
}

function projectCard(project, index) {
  const tags = (project.technologies || [])
    .slice(0, 3)
    .map((tech) => `<span class="tag">${esc(tech)}</span>`)
    .join("");

  return `<article class="project-card reveal">
        <div class="project-top">
          ${statusChip(project.status)}
          <span class="project-index">${String(index + 1).padStart(2, "0")}</span>
        </div>
        <h3 data-vt="${project.slug}"><a class="glitch" data-text="${esc(project.name)}" href="/projects/${project.slug}/">${esc(project.name)}</a></h3>
        <p>${esc(project.tagline)}</p>
        <div class="project-tags">${tags}</div>
        <div class="project-foot"><span class="go">CASE STUDY</span><span class="go" aria-hidden="true">→</span></div>
      </article>`;
}

function renderProjectCards(list) {
  return list
    .slice()
    .sort(slugOrder)
    .map((project, index) => projectCard(project, index))
    .join("\n      ");
}

function renderStack() {
  return stack
    .map(
      (group) => `<div class="stack-group reveal">
        <h3>${esc(group.group)}</h3>
        <ul class="stack-list">
          ${group.items.map((item) => `<li>${esc(item)}</li>`).join("\n          ")}
        </ul>
      </div>`
    )
    .join("\n    ");
}

function list(items) {
  return `<ul>\n${items.map((item) => `        <li>${esc(item)}</li>`).join("\n")}\n      </ul>`;
}

function caseSection(title, inner) {
  return `<section class="cs-section">
        <h2>${esc(title)}</h2>
        ${inner}
      </section>`;
}

function evidenceBlock(project) {
  const links = (project.evidence || [])
    .map(
      (item, index) =>
        `<a href="${esc(item.url)}" target="_blank" rel="noopener noreferrer">${esc(
          item.label || `Link ${index + 1}`
        )} <span aria-hidden="true">↗</span></a>`
    )
    .join("\n          ");

  const figures = (project.figures || [])
    .map(
      (figure) => `<figure class="cs-figure">
          <img src="${esc(figure.src)}" alt="${esc(figure.alt || "")}" loading="lazy" decoding="async">
          <figcaption>${esc(figure.caption || "")}</figcaption>
        </figure>`
    )
    .join("\n        ");

  return `<div class="evidence-list">
          ${links}
        </div>${figures ? `\n        ${figures}` : ""}`;
}

function caseStudy(project) {
  const sections = [];

  sections.push(caseSection("Overview", `<p>${esc(project.summary)}</p>`));
  if (project.problem) sections.push(caseSection("Problem", `<p>${esc(project.problem)}</p>`));
  if (project.solution) sections.push(caseSection("Approach", `<p>${esc(project.solution)}</p>`));
  if (project.features?.length) sections.push(caseSection("What is implemented", list(project.features)));
  if (project.contribution) sections.push(caseSection("Contribution", `<p>${esc(project.contribution)}</p>`));
  if (project.architecture) {
    sections.push(caseSection("Architecture and data flow", `<p>${esc(project.architecture)}</p>`));
  }
  if (project.technologies?.length) {
    sections.push(
      caseSection(
        "Stack",
        `<p>${project.technologies.map((tech) => `<code>${esc(tech)}</code>`).join(" ")}</p>`
      )
    );
  }
  if (project.quality?.length) sections.push(caseSection("Verification", list(project.quality)));
  if (project.evidence?.length) sections.push(caseSection("Evidence", evidenceBlock(project)));
  if (project.limitations?.length) sections.push(caseSection("Known limitations", list(project.limitations)));
  if (project.nextSteps?.length) sections.push(caseSection("Next steps", list(project.nextSteps)));

  const body = `<div class="container">
    <div class="cs">
      <nav class="breadcrumb" aria-label="Breadcrumb">
        <a href="/">Home</a><span aria-hidden="true">/</span>
        <a href="/projects/">Projects</a><span aria-hidden="true">/</span>
        <span aria-current="page">${esc(project.name)}</span>
      </nav>

      <header class="cs-hero">
        <div class="cs-kicker">
          ${statusChip(project.status)}
          <span>${esc(project.category)}</span>
          ${project.year ? `<span>${esc(project.year)}</span>` : ""}
        </div>
        <h1 data-vt="${project.slug}">${esc(project.name)}</h1>
        <p class="cs-lede">${esc(project.tagline)}</p>
        <ul class="cs-facts">
          <li><span>Status</span><strong>${STATUS_LABELS[project.status]}</strong></li>
          <li><span>Category</span><strong>${esc(project.category)}</strong></li>
          <li><span>Year</span><strong>${esc(project.year)}</strong></li>
          <li><span>Stack</span><strong>${project.technologies.length} technologies</strong></li>
        </ul>
      </header>

      <div class="cs-body">
      ${sections.join("\n      ")}
      </div>

      <div class="cs-next">
        <a class="btn primary" href="/projects/">ALL PROJECTS <span class="arrow" aria-hidden="true">→</span></a>
        <a class="btn" href="/#contact">GET IN TOUCH</a>
      </div>
    </div>
  </div>`;

  return page({
    path: `/projects/${project.slug}/`,
    title: `${project.name} — ${site.name}`,
    description: project.tagline,
    body,
    active: "projects",
    ogType: "article"
  });
}

/* ------------------------------------------------------------------ */
/* terminal payload                                                    */
/* ------------------------------------------------------------------ */

function terminalData() {
  const payload = {
    projects: published.map((project) => ({
      slug: project.slug,
      name: project.name,
      tagline: project.tagline,
      status: project.status
    })),
    stack,
    site: {
      email: site.email || "",
      github: site.github || "",
      instagram: site.instagram || ""
    }
  };

  return `<script type="application/json" id="term-data">${JSON.stringify(payload)}</script>`;
}

/* ------------------------------------------------------------------ */
/* profile                                                             */
/* ------------------------------------------------------------------ */

function renderBio() {
  const paragraphs = Array.isArray(profile.bio) ? profile.bio.filter(Boolean) : [];
  if (!paragraphs.length) return "";
  return paragraphs.map((text) => `<p>${esc(text)}</p>`).join("\n            ");
}

function renderIdentity() {
  const rows = [
    ["Name", profile.displayName],
    ["Role", profile.role],
    ["Focus", profile.focus],
    ["Based in", profile.basedIn],
    ["Studying", profile.studying],
    ["Languages", profile.languages],
    ["Build log", `${published.length} published`]
  ].filter(([, value]) => value);

  return rows
    .map(
      ([label, value]) =>
        `<div><dt>${esc(label).toUpperCase()}</dt><dd>${esc(value)}</dd></div>`
    )
    .join("\n                ");
}

