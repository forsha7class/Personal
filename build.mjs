/* pages                                                               */
/* ------------------------------------------------------------------ */

const common = {
  projectCards: renderProjectCards(featured),
  stackGroups: renderStack(),
  publishedCount: String(published.length).padStart(2, "0"),
  latestProject: (() => {
    const latest = published.slice().sort(slugOrder)[0];
    if (!latest) return "—";
    return `<a href="/projects/${latest.slug}/"><strong>${esc(latest.name)} — ${esc(
      STATUS_LABELS[latest.status]
    )}</strong></a>`;
  })()
};

const homeSource = readFileSync(join(ROOT, "src", "index.html"), "utf8");
const homeBody = fill(homeSource, {
  ...common,
  bio: renderBio(),
  identityRows: renderIdentity(),
  termData: terminalData()
});

emit(
  "index.html",
  page({
    path: "/",
    title: "DIKA/OS — I build systems, not just interfaces",
    description:
      "Dika — systems builder. Software engineering, static systems and quality engineering, with case studies that show public evidence for every claim.",
    body: homeBody,
    active: "home"
  })
);

const projectsSource = readFileSync(join(ROOT, "src", "projects", "index.html"), "utf8");
emit(
  "projects/index.html",
  page({
    path: "/projects/",
    title: `Projects — ${site.name}`,
    description:
      "Case studies for every published build: what is implemented, what is not, and how to verify it.",
    body: fill(projectsSource, common),
    active: "projects"
  })
);

for (const project of published) {
  emit(`projects/${project.slug}/index.html`, caseStudy(project));
}

/* ------------------------------------------------------------------ */
/* sitemap, robots, 404                                                */
/* ------------------------------------------------------------------ */

const sitemapEntries = [
  { path: "/", priority: "1.0" },
  { path: "/projects/", priority: "0.9" },
  ...published.map((project) => ({ path: `/projects/${project.slug}/`, priority: "0.8" }))
];

emit(
  "sitemap.xml",
  `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${sitemapEntries
  .map(
    (entry) =>
      `  <url><loc>${site.url}${entry.path}</loc><priority>${entry.priority}</priority></url>`
  )
  .join("\n")}
</urlset>
`
);

emit(
  "robots.txt",
  `User-agent: *
Allow: /

Sitemap: ${site.url}/sitemap.xml
`
);

emit(
  "404.html",
  page({
    path: "/404.html",
    title: `Not found — ${site.name}`,
    description: "This page does not exist.",
    active: "",
    extraHead: '<meta name="robots" content="noindex">',
    body: `<div class="container">
    <div class="cs">
      <div class="cs-kicker"><span>404</span><span>Not found</span></div>
      <h1>That route is not wired up.</h1>
      <p class="cs-lede">The page you asked for does not exist. The published work and the rest of the site do.</p>
      <div class="cs-next cs-next--flush">
        <a class="btn primary" href="/">BACK HOME</a>
        <a class="btn" href="/projects/">PROJECTS</a>
      </div>
    </div>
  </div>`
  })
);

/* ------------------------------------------------------------------ */
/* write or verify                                                     */
/* ------------------------------------------------------------------ */

/* remove case-study pages whose project is no longer published */
const projectsDir = join(ROOT, "projects");
if (existsSync(projectsDir)) {
  const keep = new Set(published.map((project) => project.slug));
  for (const entry of readdirSync(projectsDir, { withFileTypes: true })) {
    if (!entry.isDirectory() || keep.has(entry.name)) continue;
    const file = join(projectsDir, entry.name, "index.html");
    if (!existsSync(file)) continue;
    if (!readFileSync(file, "utf8").startsWith(MARKER)) continue;
    if (!CHECK) rmSync(join(projectsDir, entry.name), { recursive: true, force: true });
    notes.push(`${entry.name}: unpublished — stale generated page ${CHECK ? "detected" : "removed"}`);
  }
}

let drift = 0;
for (const [relPath, content] of outputs) {
  const abs = join(ROOT, relPath);
  const current = existsSync(abs) ? readFileSync(abs, "utf8") : null;

  if (current === content) continue;
  drift += 1;

  if (CHECK) {
    console.log(`drift: ${relPath}`);
  } else {
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, content);
    console.log(`wrote: ${relPath}`);
  }
}

for (const note of notes) console.log(`note: ${note}`);

if (CHECK) {
  if (drift > 0) {
    console.error(`\n✗ ${drift} generated file(s) out of date. Run: node build.mjs`);
    process.exit(1);
  }
  console.log(`✓ generated output is up to date (${outputs.size} files, ${published.length} published projects)`);
} else {
  console.log(
    `\n✓ build complete — ${outputs.size} files, ${published.length} published, ${
      projects.length - published.length
    } withheld`
  );
}
